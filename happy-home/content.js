const bossNames = ['Клубок-ураган', 'Мистер Ветерок', 'Шар-переросток', 'Орбитальный хранитель', 'Большой Домовой-Беспорядок'];
export const levels = heroes.map((hero, li) => ({
  ...hero,
  id: li + 1,
  rounds: rounds[li].map(([title, brief, mechanic], ri) => {
    const n = li * 10 + ri + 1;
    return {
      id: n, level: li + 1, round: ri + 1, title, brief, mechanic, pattern: patterns[li][ri],
      boss: ri === 9 ? bossNames[li] : null,
      duration: Math.round(120 * (1.1 ** ri) * (1.1 ** li)),
      targetSeconds: Math.round(120 * (1.1 ** ri) * (1.1 ** li)),
      themeColor: hero.color,
    };
  }),
}));

export const getRound = (id) => levels[Math.floor((id - 1) / 10)]?.rounds[(id - 1) % 10];
export const durationLabel = (seconds) => `${Math.floor(seconds / 60)}:${String(seconds % 60).padStart(2, '0')}`;
